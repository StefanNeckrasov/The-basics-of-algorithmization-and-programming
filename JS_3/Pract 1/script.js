var date = new Date();
alert("Текущий День: " +date.getDate()); //дни
alert("Текущий Месяц: " +date.getMonth()); //месяцы
alert("Текущий Год: "+date.getFullYear()); //год


alert(date.getMilliseconds()); //миллисекунды
alert(date.getSeconds()); //секунды
alert(date.getMinutes()); //минуты
alert(date.getHours()); //часы
